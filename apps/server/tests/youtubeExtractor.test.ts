import { afterEach, describe, expect, it, vi } from 'vitest'
import { ERROR_CODES } from '@sidekick/shared'
import {
  extractYoutubeTranscript,
  fetchTimedText,
  formatTimestamp,
  parseTimedTextXml,
} from '../src/lib/youtubeExtractor.js'
import { SafeFetchError } from '../src/lib/safeFetch.js'

/**
 * Unit test cho YouTube transcript extractor — T-M1-22.
 *
 * Mock `globalThis.fetch` de khong phu thuoc mang.
 *
 * Docs: docs/SYSTEM_DESIGN.md §7.3.1
 */

const WATCH_HTML = `
  <html><head>
    <script>var ytInitialData = {"INNERTUBE_API_KEY":"AIzaSyTESTKEY","VISITOR_DATA":"Cgt2aXNpdG9y"};</script>
  </head><body></body></html>
`

const PLAYER_RESPONSE = {
  videoDetails: { title: 'Video hoc Sidekick AI' },
  playabilityStatus: { status: 'OK' },
  captions: {
    playerCaptionsTracklistRenderer: {
      captionTracks: [
        {
          baseUrl: 'https://www.youtube.com/api/timedtext?v=abc&lang=vi',
          languageCode: 'vi',
          kind: 'asr',
          name: { simpleText: 'Vietnamese' },
        },
        {
          baseUrl: 'https://www.youtube.com/api/timedtext?v=abc&lang=en',
          languageCode: 'en',
          name: { simpleText: 'English' },
        },
      ],
    },
  },
}

const TIMEDTEXT_XML = `<?xml version="1.0" encoding="utf-8"?>
<transcript>
  <text start="0" dur="2000">Xin chao cac ban</text>
  <text start="2000" dur="2500">Chung ta bat dau</text>
</transcript>`

/** Tao mock fetch tra ve tung response theo thu tu URL. */
function mockFetch(handlers: Array<(url: string, init?: RequestInit) => Response>): void {
  let index = 0
  vi.stubGlobal('fetch', (input: string | URL | Request, init?: RequestInit) => {
    const url = typeof input === 'string' ? input : input.toString()
    const handler = handlers[index]
    index += 1
    if (handler === undefined) {
      return Promise.reject(new Error(`Khong co mock cho ${url}`))
    }
    return Promise.resolve(handler(url, init))
  })
}

afterEach(() => {
  vi.unstubAllGlobals()
})

describe('parseTimedTextXml', () => {
  it('parse format 3 (`<p t d>`) thanh `[mm:ss] text`', () => {
    const segments = parseTimedTextXml(
      '<transcript><p t="0" d="2000">Xin chao</p><p t="65000" d="1000">Bai viet</p></transcript>',
    )
    expect(segments).toEqual(['[00:00] Xin chao', '[01:05] Bai viet'])
  })

  it('parse format 4 (`<text start dur>`) thanh `[mm:ss] text`', () => {
    const segments = parseTimedTextXml(TIMEDTEXT_XML)
    expect(segments).toEqual(['[00:00] Xin chao cac ban', '[00:02] Chung ta bat dau'])
  })

  it('giai ma entity XML', () => {
    const segments = parseTimedTextXml('<p t="0" d="1">A &amp; B &lt;x&gt;</p>')
    expect(segments).toEqual(['[00:00] A & B <x>'])
  })

  it('bo qua segment rong', () => {
    const segments = parseTimedTextXml('<p t="0" d="1"></p><p t="1000" d="1">   </p>')
    expect(segments).toEqual([])
  })
})

describe('formatTimestamp', () => {
  it('format mm:ss va h:mm:ss', () => {
    expect(formatTimestamp(0)).toBe('00:00')
    expect(formatTimestamp(65_000)).toBe('01:05')
    expect(formatTimestamp(3_725_000)).toBe('1:02:05')
  })
})

describe('extractYoutubeTranscript', () => {
  it('lay transcript qua InnerTube + timedtext', async () => {
    mockFetch([
      () => new Response(WATCH_HTML, { status: 200 }),
      () => new Response(JSON.stringify(PLAYER_RESPONSE), { status: 200 }),
      () => new Response(TIMEDTEXT_XML, { status: 200 }),
    ])

    const result = await extractYoutubeTranscript('https://www.youtube.com/watch?v=abc')

    expect(result.text).toContain('[00:00] Xin chao cac ban')
    expect(result.title).toBe('Video hoc Sidekick AI')
    expect(result.language).toBe('vi')
    expect(result.isAutoGenerated).toBe(true)
  })

  it('uu tien tieng Viet khi co nhieu track', async () => {
    mockFetch([
      () => new Response(WATCH_HTML, { status: 200 }),
      () => new Response(JSON.stringify(PLAYER_RESPONSE), { status: 200 }),
      () => new Response(TIMEDTEXT_XML, { status: 200 }),
    ])

    const result = await extractYoutubeTranscript('https://youtu.be/abc')
    expect(result.language).toBe('vi')
  })

  it('nem CONTEXT_TRANSCRIPT_UNAVAILABLE khi video khong co caption', async () => {
    mockFetch([
      () => new Response(WATCH_HTML, { status: 200 }),
      () =>
        new Response(
          JSON.stringify({
            videoDetails: { title: 'Khong caption' },
            playabilityStatus: { status: 'OK' },
          }),
          { status: 200 },
        ),
    ])

    await expect(
      extractYoutubeTranscript('https://www.youtube.com/watch?v=abc'),
    ).rejects.toMatchObject({ code: ERROR_CODES.CONTEXT_TRANSCRIPT_UNAVAILABLE })
  })

  it('nem CONTEXT_TRANSCRIPT_UNAVAILABLE khi khong lay duoc API key', async () => {
    mockFetch([() => new Response('<html></html>', { status: 200 })])

    await expect(
      extractYoutubeTranscript('https://www.youtube.com/watch?v=abc'),
    ).rejects.toMatchObject({ code: ERROR_CODES.CONTEXT_TRANSCRIPT_UNAVAILABLE })
  })

  it('nem CONTEXT_TRANSCRIPT_UNAVAILABLE khi player response khong phai JSON', async () => {
    mockFetch([
      () => new Response(WATCH_HTML, { status: 200 }),
      () => new Response('<html>loi</html>', { status: 200 }),
    ])

    await expect(
      extractYoutubeTranscript('https://www.youtube.com/watch?v=abc'),
    ).rejects.toBeInstanceOf(SafeFetchError)
  })
})

describe('fetchTimedText', () => {
  it('tra ve danh sach segment da format', async () => {
    mockFetch([() => new Response(TIMEDTEXT_XML, { status: 200 })])

    const segments = await fetchTimedText('https://www.youtube.com/api/timedtext?v=abc')
    expect(segments).toHaveLength(2)
    expect(segments[0]).toBe('[00:00] Xin chao cac ban')
  })
})
